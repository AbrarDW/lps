type appView struct {
	*store.App
	State      string            `json:"state"`
	Error      string            `json:"error,omitempty"`
	Deploying  bool              `json:"deploying"`
	LastDeploy *store.Deployment `json:"lastDeploy,omitempty"`
	// Remote URLs, set when remote access is active for this app.
	RemoteURL string `json:"remoteUrl,omitempty"`
	PublicURL string `json:"publicUrl,omitempty"`
	// Cloudflare quick link: starting | active | error, its address and any error.
	QuickState string `json:"quickState,omitempty"`
	QuickURL   string `json:"quickUrl,omitempty"`
	QuickError string `json:"quickError,omitempty"`
	// HasGitToken tells the UI an access token is stored (it is never returned).
	HasGitToken bool `json:"hasGitToken,omitempty"`
	// DockerfileSource is "lps" when LPS's stored Dockerfile is used, "project"
	// for the project's own, and "none" for apps that run inside a VPS.
	DockerfileSource string `json:"dockerfileSource"`
	// VPSName is the VPS the app runs in, if any.
	VPSName string `json:"vpsName,omitempty"`
	// LocalURL is the app's name-based address on this PC (http://<app>.localhost:7070).
	LocalURL string `json:"localUrl,omitempty"`
	// PathURL is its name-based address on the tailnet (https://<pc>.ts.net:8080/<app>/).
	PathURL string `json:"pathUrl,omitempty"`
}

// maxDockerfile caps a stored Dockerfile (requests are limited to 64 KiB).
const maxDockerfile = 32 << 10

type createAppReq struct {
	Name          string  `json:"name"`
	SourcePath    string  `json:"sourcePath"`
	ContainerPort int     `json:"containerPort"`
	CPUs          float64 `json:"cpus"`
	MemoryMB      int     `json:"memoryMb"`
	// Dockerfile is used when the project has none (usually generated by /apps/detect).
	Dockerfile string `json:"dockerfile"`
	// SaveToProject writes Dockerfile into the project folder instead of storing it in LPS.
	SaveToProject bool `json:"saveToProject"`

	// VPSID runs the app inside that VPS instead of its own container.
	VPSID      int64  `json:"vpsId"`
	SourceKind string `json:"sourceKind"` // "pc" (SourcePath), "vps" (VPSPath) or "git" (GitURL)
	VPSPath    string `json:"vpsPath"`
	Packages   string `json:"packages"`
	InstallCmd string `json:"installCmd"`
	StartCmd   string `json:"startCmd"`

	// Git source (SourceKind "git").
	GitURL     string `json:"gitUrl"`
	GitBranch  string `json:"gitBranch"`
	GitToken   string `json:"gitToken"`
	AutoDeploy bool   `json:"autoDeploy"`
}

func cleanSourcePath(p string) (string, error) {
	if !filepath.IsAbs(p) {
		return "", errors.New("sourcePath must be an absolute path on the host PC (e.g. C:\\projects\\my-app)")
	}
	p = filepath.Clean(p)
	return p, builder.ValidateDir(p)
}

func validateDockerfile(df string) error {
	if len(df) > maxDockerfile {
		return fmt.Errorf("dockerfile is too large (max %d KB)", maxDockerfile>>10)
	}
	if !strings.Contains(strings.ToUpper(df), "FROM ") {
		return errors.New("dockerfile must contain a FROM line")
	}
	return nil
}

func (req *createAppReq) validate() error {
	if !nameRe.MatchString(req.Name) {
		return errors.New("name must be 2-31 chars: lowercase letters, digits and '-'")
	}
	if req.VPSID > 0 {
		return req.validateVPS()
	}
	req.VPSPath, req.Packages, req.InstallCmd, req.StartCmd = "", "", "", ""
	git := req.SourceKind == store.SourceGit
	if git {
		if err := req.validateGit(); err != nil {
			return err
		}
	} else {
		req.SourceKind, req.GitURL, req.GitBranch, req.GitToken, req.AutoDeploy = store.SourcePC, "", "", "", false
		var err error
		if req.SourcePath, err = cleanSourcePath(req.SourcePath); err != nil {
			return err
		}
	}
	if strings.TrimSpace(req.Dockerfile) == "" {
		req.Dockerfile = ""
		// A repository is only checked at the first deploy; "Check repository"
		// in the form already told the user whether it has a Dockerfile.
		if !git && !builder.HasDockerfile(req.SourcePath) {
			return errors.New("no Dockerfile found in the project folder: use the generated Dockerfile in the form, or add one to the folder")
		}
	} else if err := validateDockerfile(req.Dockerfile); err != nil {
		return err
	}
	if req.ContainerPort < 1 || req.ContainerPort > 65535 {
		return errors.New("containerPort must be 1-65535 (the port your app listens on inside the container)")
	}
	return validateResources(req.CPUs, req.MemoryMB)
}

func (s *Server) appView(r *http.Request, a *store.App) appView {
	view := appView{App: a, DockerfileSource: "project"}
	if a.Dockerfile != "" {
		view.DockerfileSource = "lps"
	}
	if a.InVPS() {
		view.DockerfileSource = "none"
		if v, err := s.store.GetVPS(r.Context(), a.VPSID); err == nil {
			view.VPSName = v.Name
		}
	}
	view.LocalURL = s.localAppURL(a)
	s.quickView(r.Context(), a, &view)
	view.HasGitToken = a.GitToken != ""
	if dns, active := s.remoteSnapshot(r.Context()); dns != "" {
		if e, ok := active[a.HostPort]; ok {
			view.RemoteURL = remoteURL(dns, toExposure(e))
		}
		if e, ok := active[appsRemotePort]; ok && e.LocalPort == s.cfg.GatewayPort {
			view.PathURL = remoteURL(dns, toExposure(e)) + "/" + a.Name + "/"
		}
		if e, ok := active[a.PublicPort]; ok && a.PublicPort > 0 && e.Public {
			view.PublicURL = remoteURL(dns, toExposure(e))
		}
	}
	s.mu.Lock()
	view.Deploying = s.deploying[a.ID]
	s.mu.Unlock()
	if ds, err := s.store.ListDeployments(r.Context(), a.ID, 1); err == nil && len(ds) > 0 {
		d := ds[0]
		d.Log = "" // full logs via /deployments
		view.LastDeploy = d
	}
	var st string
	var err error
	if a.InVPS() {
		st, err = s.vpsAppState(r.Context(), a)
	} else {
		st, err = s.engine.State(r.Context(), a.ContainerID)
	}
	if err != nil {
		view.State, view.Error = stateError, err.Error()
	} else {
		view.State = st
	}
	return view
}

func (s *Server) handleListApps(w http.ResponseWriter, r *http.Request) {
	list, err := s.store.ListApps(r.Context())
	if err != nil {
		s.internalError(w, err)
		return
	}
	out := make([]appView, 0, len(list))
	for _, a := range list {
		out = append(out, s.appView(r, a))
	}
	writeJSON(w, 200, out)
}

func (s *Server) handleCreateApp(w http.ResponseWriter, r *http.Request) {
	var req createAppReq
	if !decode(w, r, &req) {
		return
	}
	if err := req.validate(); err != nil {
		writeError(w, 400, err.Error())
		return
	}
	if req.VPSID > 0 {
		v, err := s.store.GetVPS(r.Context(), req.VPSID)
		if err != nil {
			if errors.Is(err, store.ErrNotFound) {
				writeError(w, 400, "that VPS does not exist")
			} else {
				s.internalError(w, err)
			}
			return
		}
		others, err := s.store.ListAppsByVPS(r.Context(), v.ID)
		if err != nil {
			s.internalError(w, err)
			return
		}
		for _, o := range others {
			if o.ContainerPort == req.ContainerPort {
				writeError(w, http.StatusConflict, fmt.Sprintf("app %s already uses port %d in VPS %s; pick another port (your app gets it as $PORT)",
					o.Name, o.ContainerPort, v.Name))
				return
			}
		}
	}
	if req.SaveToProject && req.Dockerfile != "" {
		if err := writeProjectDockerfile(req.SourcePath, req.Dockerfile); err != nil {
			writeError(w, http.StatusConflict, err.Error())
			return
		}
		req.Dockerfile = "" // the project's file is now the source of truth
	}
	if req.SourceKind == store.SourceGit {
		req.SourcePath = s.gitDir(req.Name)
	}
	port, err := s.reservePort(r.Context(), s.cfg.AppPortMin, s.cfg.AppPortMax)
	if err != nil {
		writeError(w, http.StatusConflict, err.Error())
		return
	}
	defer s.releasePort(port)
	a := &store.App{
		Name: req.Name, SourcePath: req.SourcePath, ContainerPort: req.ContainerPort,
		HostPort: port, CPUs: req.CPUs, MemoryMB: req.MemoryMB, Dockerfile: req.Dockerfile,
		VPSID: req.VPSID, SourceKind: req.SourceKind, VPSPath: req.VPSPath,
		Packages: req.Packages, InstallCmd: req.InstallCmd, StartCmd: req.StartCmd,
		GitURL: req.GitURL, GitBranch: req.GitBranch, GitToken: req.GitToken, AutoDeploy: req.AutoDeploy,
	}
	if err := s.store.CreateApp(r.Context(), a); err != nil {
		storeError(s, w, err, "app")
		return
	}
	where := "in its own container"
	if a.InVPS() {
		where = "in a VPS"
	}
	if a.SourceKind == store.SourceGit {
		where += ", from " + a.GitURL
	}
	s.info(r, "app.created", subjApp, a.ID, a.Name, "Created app %s (%s)", a.Name, where)
	if _, err := s.startDeploy(a); err != nil {
		s.internalError(w, err)
		return
	}
	s.kickRemote()
	writeJSON(w, http.StatusAccepted, s.appView(r, a))
}

func (s *Server) loadApp(w http.ResponseWriter, r *http.Request) (*store.App, bool) {
	id, err := strconv.ParseInt(chi.URLParam(r, "id"), 10, 64)
	if err != nil {
		writeError(w, 400, "invalid id")
		return nil, false
	}
	a, err := s.store.GetApp(r.Context(), id)
	if err != nil {
		storeError(s, w, err, "app")
		return nil, false
	}
	return a, true
}

func (s *Server) handleGetApp(w http.ResponseWriter, r *http.Request) {
	if a, ok := s.loadApp(w, r); ok {
		writeJSON(w, 200, s.appView(r, a))
	}
}

var errDeployInProgress = errors.New("a deployment is already in progress")

// startDeploy records a deployment and builds+runs it in the background.
func (s *Server) startDeploy(a *store.App) (*store.Deployment, error) {
	s.mu.Lock()
	if s.deploying[a.ID] {
		s.mu.Unlock()
		return nil, errDeployInProgress
	}
	s.deploying[a.ID] = true
	s.mu.Unlock()

	d, err := s.store.CreateDeployment(s.ctx, a.ID)
	if err != nil {
		s.mu.Lock()
		delete(s.deploying, a.ID)
		s.mu.Unlock()
		return nil, err
	}
	buf := &syncBuffer{}
	s.mu.Lock()
	s.liveLogs[d.ID] = buf
	s.mu.Unlock()

	// The goroutine gets its own copy: the caller keeps using a (e.g. to
	// encode the HTTP response) while the deploy updates ContainerID.
	app := *a
	s.wg.Add(1)
	go func() {
		defer s.wg.Done()
		a := &app
		image, err := s.runDeploy(a, d, buf)
		status := store.DeployRunning
		if err != nil {
			fmt.Fprintf(buf, "\n[lps] deployment failed: %v\n", err)
			status = store.DeployFailed
		} else {
			fmt.Fprintf(buf, "\n[lps] deployed; serving on %s:%d\n", s.cfg.BindIP, a.HostPort)
		}
		if ferr := s.store.FinishDeployment(s.ctx, d.ID, status, image, buf.String()); ferr != nil {
			s.log.Error("finish deployment", "err", ferr)
		}
		if err != nil {
			s.fail(nil, "app.deploy_failed", subjApp, a.ID, a.Name, "Deploy #%d of %s failed: %s", d.ID, a.Name, firstLine(err.Error()))
		} else if hash := s.finishGitDeploy(a, d); hash != "" {
			s.info(nil, "app.deployed", subjApp, a.ID, a.Name, "Deploy #%d of %s is running (commit %s)", d.ID, a.Name, shortHash(hash))
		} else {
			s.info(nil, "app.deployed", subjApp, a.ID, a.Name, "Deploy #%d of %s is running", d.ID, a.Name)
		}
		if err == nil && !a.InVPS() {
			s.pruneImages(a.Name, keepImages)
		}
		if err == nil && a.QuickLink {
			s.kickQuick() // a new app container joins lps-net
		}
		s.mu.Lock()
		delete(s.deploying, a.ID)
		delete(s.liveLogs, d.ID)
		s.mu.Unlock()
	}()
	return d, nil
}

// keepImages is how many recent successful app images are kept: the live one
// and the one before it.
const keepImages = 2

// pruneImages deletes an app's old images (lps-app-<name>:<deployment>),
// keeping the newest keep: the live one and the previous one. Without it every
// redeploy leaves another image behind. keep 0 removes them all.
func (s *Server) pruneImages(name string, keep int) {
	tags, err := s.engine.ImageTags(s.ctx, "lps-app-"+name)
	if err != nil {
		s.log.Warn("list app images", "app", name, "err", err)
		return
	}
	num := func(t string) int { n, _ := strconv.Atoi(t[strings.LastIndexByte(t, ':')+1:]); return n }
	sort.Slice(tags, func(i, j int) bool { return num(tags[i]) > num(tags[j]) })
	for i, t := range tags {
		if i < keep {
			continue
		}
		if err := s.engine.RemoveImage(s.ctx, t); err != nil {
			s.log.Warn("remove old image", "image", t, "err", err)
		}
	}
}

func (s *Server) runDeploy(a *store.App, d *store.Deployment, log io.Writer) (string, error) {
	if err := s.prepareSource(a, d, log); err != nil {
		return "", err
	}
	if a.InVPS() {
		return s.runVPSDeploy(a, log)
	}
	ctx := s.ctx
	if err := builder.ValidateDir(a.SourcePath); err != nil {
		return "", err
	}
	dockerfile, extra := "Dockerfile", map[string][]byte(nil)
	if a.Dockerfile != "" {
		dockerfile = builder.GeneratedDockerfile
		extra = map[string][]byte{dockerfile: []byte(a.Dockerfile)}
	} else if !builder.HasDockerfile(a.SourcePath) {
		return "", errors.New("the project folder no longer has a Dockerfile; add one or set a Dockerfile on the app page")
	}
	image := fmt.Sprintf("lps-app-%s:%d", a.Name, d.ID)
	source := "the project's Dockerfile"
	if a.Dockerfile != "" {
		source = "the Dockerfile stored in LPS"
	}
	fmt.Fprintf(log, "[lps] building %s from %s using %s\n", image, a.SourcePath, source)

	pr, pw := io.Pipe()
	go func() { pw.CloseWithError(builder.TarDir(a.SourcePath, pw, extra)) }()
	err := s.engine.BuildImage(ctx, pr, image, dockerfile, log)
	pr.CloseWithError(err) // unblock the tar writer if the build stopped early
	if err != nil {
		return "", fmt.Errorf("build: %w", err)
	}

	fmt.Fprintln(log, "[lps] replacing container")
	if err := s.engine.Remove(ctx, a.ContainerID); err != nil {
		return image, fmt.Errorf("remove old container: %w", err)
	}
	_ = s.engine.Remove(ctx, docker.AppContainerName(a.Name))
	vars, err := s.store.AppEnv(ctx, a.ID)
	if err != nil {
		return image, err
	}
	if len(vars) > 0 {
		fmt.Fprintf(log, "[lps] environment: %d variable(s)\n", len(vars))
	}
	cid, err := s.engine.CreateApp(ctx, docker.AppSpec{
		Name: a.Name, Image: image, ContainerPort: a.ContainerPort, HostPort: a.HostPort,
		CPUs: a.CPUs, MemoryMB: a.MemoryMB, Env: envList(vars),
	})
	if err != nil {
		return image, fmt.Errorf("create container: %w", err)
	}
	if err := s.store.SetAppContainer(ctx, a.ID, cid); err != nil {
		return image, err
	}
	a.ContainerID = cid
	if err := s.engine.Start(ctx, cid); err != nil {
		return image, fmt.Errorf("start: %w", err)
	}
	return image, nil
}

func (s *Server) handleDeployApp(w http.ResponseWriter, r *http.Request) {
	a, ok := s.loadApp(w, r)
	if !ok {
		return
	}
	d, err := s.startDeploy(a)
	if errors.Is(err, errDeployInProgress) {
		writeError(w, http.StatusConflict, err.Error())
		return
	}
	if err != nil {
		s.internalError(w, err)
		return
	}
	s.info(r, "app.redeploy", subjApp, a.ID, a.Name, "Redeploy #%d of %s started", d.ID, a.Name)
	writeJSON(w, http.StatusAccepted, d)
}

func (s *Server) handleAppAction(action string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		a, ok := s.loadApp(w, r)
		if !ok {
			return
		}
		if a.ContainerID == "" {
			writeError(w, http.StatusConflict, "app has not been deployed successfully yet")
			return
		}
		var err error
		if a.InVPS() {
			err = s.vpsAppAction(r.Context(), a, action)
		} else if action == "start" {
			err = s.engine.Start(r.Context(), a.ContainerID)
		} else {
			err = s.engine.Stop(r.Context(), a.ContainerID)
		}
		if err != nil {
			writeError(w, http.StatusBadGateway, action+" failed: "+err.Error())
			return
		}
		if action == "start" {
			s.info(r, "app.started", subjApp, a.ID, a.Name, "Started app %s", a.Name)
		} else {
			s.info(r, "app.stopped", subjApp, a.ID, a.Name, "Stopped app %s", a.Name)
		}
		writeJSON(w, 200, s.appView(r, a))
	}
}

func (s *Server) handleDeleteApp(w http.ResponseWriter, r *http.Request) {
	a, ok := s.loadApp(w, r)
	if !ok {
		return
	}
	s.mu.Lock()
	busy := s.deploying[a.ID]
	s.mu.Unlock()
	if busy {
		writeError(w, http.StatusConflict, errDeployInProgress.Error())
		return
	}
	if a.InVPS() {
		if err := s.removeVPSApp(r.Context(), a); err != nil {
			writeError(w, http.StatusBadGateway, "remove relay: "+err.Error())
			return
		}
	} else {
		if err := s.engine.Remove(r.Context(), a.ContainerID); err != nil {
			writeError(w, http.StatusBadGateway, "remove container: "+err.Error())
			return
		}
		_ = s.engine.Remove(r.Context(), docker.AppContainerName(a.Name))
		s.pruneImages(a.Name, 0)
	}
	if err := s.store.DeleteApp(r.Context(), a.ID); err != nil {
		s.internalError(w, err)
		return
	}
	if a.SourceKind == store.SourceGit {
		_ = os.RemoveAll(a.SourcePath) // LPS's own clone, not the user's code
	}
	_ = s.engine.RemoveQuickLink(r.Context(), a.Name) // the loop retries if this fails
	s.warn(r, "app.deleted", subjApp, a.ID, a.Name, "Deleted app %s", a.Name)
	s.kickRemote()
	s.kickQuick()
	w.WriteHeader(http.StatusNoContent)
}

