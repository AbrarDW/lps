// writeProjectDockerfile creates Dockerfile (and .dockerignore if missing) in
// dir, refusing to overwrite an existing Dockerfile.
func writeProjectDockerfile(dir, content string) error {
	f, err := os.OpenFile(filepath.Join(dir, "Dockerfile"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if errors.Is(err, fs.ErrExist) {
		return errors.New("the project folder already has a Dockerfile; LPS will not overwrite it")
	}
	if err != nil {
		return fmt.Errorf("write Dockerfile: %w", err)
	}
	if _, err := f.WriteString(content); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	ig, err := os.OpenFile(filepath.Join(dir, ".dockerignore"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err == nil {
		_, err = ig.WriteString(builder.DefaultDockerignore)
		ig.Close()
	}
	if err != nil && !errors.Is(err, fs.ErrExist) {
		return fmt.Errorf("write .dockerignore: %w", err)
	}
	return nil
}

type detectResp struct {
	HasDockerfile     bool                `json:"hasDockerfile"`
	ProjectDockerfile string              `json:"projectDockerfile,omitempty"`
	Detection         builder.Detection   `json:"detection"`
	Templates         []builder.Detection `json:"templates"`
}

// handleDetectApp inspects a project folder and proposes a Dockerfile.
func (s *Server) handleDetectApp(w http.ResponseWriter, r *http.Request) {
	var req struct {
		SourcePath string `json:"sourcePath"`
	}
	if !decode(w, r, &req) {
		return
	}
	dir, err := cleanSourcePath(req.SourcePath)
	if err != nil {
		writeError(w, 400, err.Error())
		return
	}
	writeJSON(w, 200, detectResp{
		HasDockerfile:     builder.HasDockerfile(dir),
		ProjectDockerfile: readProjectDockerfile(dir),
		Detection:         builder.Detect(dir),
		Templates:         builder.Templates(dir),
	})
}

func readProjectDockerfile(dir string) string {
	f, err := os.Open(filepath.Join(dir, "Dockerfile"))
	if err != nil {
		return ""
	}
	defer f.Close()
	b, _ := io.ReadAll(io.LimitReader(f, maxDockerfile))
	return string(b)
}

// handleGetAppDockerfile returns the Dockerfile an app builds with.
func (s *Server) handleGetAppDockerfile(w http.ResponseWriter, r *http.Request) {
	a, ok := s.loadApp(w, r)
	if !ok {
		return
	}
	resp := map[string]any{"source": "project", "dockerfile": readProjectDockerfile(a.SourcePath),
		"projectHasDockerfile": builder.HasDockerfile(a.SourcePath)}
	if a.Dockerfile != "" {
		resp["source"], resp["dockerfile"] = "lps", a.Dockerfile
	}
	if a.Dockerfile == "" && !builder.HasDockerfile(a.SourcePath) {
		resp["suggested"] = builder.Detect(a.SourcePath)
	}
	writeJSON(w, 200, resp)
}

// handleSetAppDockerfile stores (or clears, to use the project's) the app's
// Dockerfile and redeploys.
func (s *Server) handleSetAppDockerfile(w http.ResponseWriter, r *http.Request) {
	a, ok := s.loadApp(w, r)
	if !ok {
		return
	}
	var req struct {
		Dockerfile string `json:"dockerfile"`
	}
	if !decode(w, r, &req) {
		return
	}
	if strings.TrimSpace(req.Dockerfile) == "" {
		req.Dockerfile = ""
		if !builder.HasDockerfile(a.SourcePath) {
			writeError(w, 400, "the project folder has no Dockerfile, so LPS needs one stored for this app")
			return
		}
	} else if err := validateDockerfile(req.Dockerfile); err != nil {
		writeError(w, 400, err.Error())
		return
	}
	if err := s.store.SetAppDockerfile(r.Context(), a.ID, req.Dockerfile); err != nil {
		s.internalError(w, err)
		return
	}
	a.Dockerfile = req.Dockerfile
	if req.Dockerfile == "" {
		s.info(r, "app.dockerfile", subjApp, a.ID, a.Name, "%s now builds with the project's Dockerfile", a.Name)
	} else {
		s.info(r, "app.dockerfile", subjApp, a.ID, a.Name, "Dockerfile of %s changed", a.Name)
	}
	if _, err := s.startDeploy(a); errors.Is(err, errDeployInProgress) {
		writeError(w, http.StatusConflict, "saved, but a deployment is already running; redeploy when it finishes")
		return
	} else if err != nil {
		s.internalError(w, err)
		return
	}
	writeJSON(w, 200, s.appView(r, a))
}
