// Detection is a generated Dockerfile for a project without one.
type Detection struct {
	Type       string   `json:"type"`  // template id, e.g. "node-next"
	Label      string   `json:"label"` // human-readable, e.g. "Node.js · Next.js"
	Port       int      `json:"port"`  // port the app listens on inside the container
	Dockerfile string   `json:"dockerfile"`
	Notes      []string `json:"notes"`
	// Run is how to run the same project directly inside an LPS VPS.
	Run RunSetup `json:"run"`
}

// RunSetup is how an app is installed and started inside a VPS (no Docker build).
type RunSetup struct {
	Packages string   `json:"packages"` // Ubuntu packages, space-separated
	Install  string   `json:"install"`  // run in the app folder on each deploy
	Start    string   `json:"start"`    // long-running; $PORT holds the port
	Port     int      `json:"port"`
	Notes    []string `json:"notes"`
}

// project holds facts gathered from a project folder.
type project struct {
	dir     string
	pkg     *packageJSON
	pyDeps  string // lower-cased requirements.txt + pyproject.toml
	pkgMgr  string // npm | yarn | pnpm
	hasLock bool
}

type packageJSON struct {
	Name            string            `json:"name"`
	Main            string            `json:"main"`
	Scripts         map[string]string `json:"scripts"`
	Dependencies    map[string]string `json:"dependencies"`
	DevDependencies map[string]string `json:"devDependencies"`
}

func (p *packageJSON) has(dep string) bool {
	if p == nil {
		return false
	}
	_, a := p.Dependencies[dep]
	_, b := p.DevDependencies[dep]
	return a || b
}

// A project with dir "" has no files: Templates("") renders generic templates.
func (p *project) exists(rel string) bool {
	if p.dir == "" {
		return false
	}
	_, err := os.Stat(filepath.Join(p.dir, filepath.FromSlash(rel)))
	return err == nil
}

func (p *project) read(rel string) string {
	if p.dir == "" {
		return ""
	}
	b, err := os.ReadFile(filepath.Join(p.dir, filepath.FromSlash(rel)))
	if err != nil {
		return ""
	}
	return string(b)
}

func inspect(dir string) *project {
	p := &project{dir: dir, pkgMgr: "npm"}
	if raw := p.read("package.json"); raw != "" {
		var pkg packageJSON
		if json.Unmarshal([]byte(raw), &pkg) == nil {
			p.pkg = &pkg
		} else {
			p.pkg = &packageJSON{}
		}
	}
	switch {
	case p.exists("pnpm-lock.yaml"):
		p.pkgMgr, p.hasLock = "pnpm", true
	case p.exists("yarn.lock"):
		p.pkgMgr, p.hasLock = "yarn", true
	case p.exists("package-lock.json"):
		p.hasLock = true
	}
	p.pyDeps = strings.ToLower(p.read("requirements.txt") + "\n" + p.read("pyproject.toml"))
	return p
}

// ---- Node helpers ----

func (p *project) nodeInstall() string {
	switch p.pkgMgr {
	case "pnpm":
		return "corepack enable && pnpm install --frozen-lockfile"
	case "yarn":
		return "corepack enable && yarn install --frozen-lockfile"
	}
	if p.hasLock {
		return "npm ci"
	}
	return "npm install"
}

// nodeInstallVPS avoids corepack, which Ubuntu's nodejs package lacks.
func (p *project) nodeInstallVPS() string {
	switch p.pkgMgr {
	case "pnpm":
		return "npx --yes pnpm install --frozen-lockfile"
	case "yarn":
		return "npx --yes yarn install --frozen-lockfile"
	}
	return p.nodeInstall()
}

func (p *project) nodeRunVPS(script string) string {
	switch p.pkgMgr {
	case "pnpm":
		return "npx --yes pnpm run " + script
	case "yarn":
		return "npx --yes yarn " + script
	}
	return p.nodeRun(script)
}

const nodePackages = "nodejs npm"

func (p *project) nodeRun(script string) string {
	switch p.pkgMgr {
	case "pnpm":
		return "pnpm run " + script
	case "yarn":
		return "yarn " + script
	}
	if script == "start" {
		return "npm start"
	}
	return "npm run " + script
}

func execForm(cmd string) string {
	parts := strings.Fields(cmd)
	quoted := make([]string, len(parts))
	for i, s := range parts {
		quoted[i] = `"` + s + `"`
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

const nodeCopyManifests = "COPY package.json package-lock.json* yarn.lock* pnpm-lock.yaml* ./"

func nodeNext(p *project) Detection {
	return Detection{
		Type: "node-next", Label: "Node.js · Next.js", Port: 3000,
		Dockerfile: strings.Join([]string{
			"# Generated by LPS for a Next.js app. Edit as needed.",
			"FROM node:22-alpine",
			"WORKDIR /app",
			nodeCopyManifests,
			"RUN " + p.nodeInstall(),
			"COPY . .",
			"RUN " + p.nodeRun("build"),
			"ENV NODE_ENV=production PORT=3000 HOSTNAME=0.0.0.0",
			"EXPOSE 3000",
			"CMD " + execForm(p.nodeRun("start")),
		}, "\n") + "\n",
		Notes: []string{"Runs `" + p.nodeRun("build") + "` then `" + p.nodeRun("start") + "`."},
		Run: RunSetup{
			Packages: nodePackages, Port: 3000,
			Install: p.nodeInstallVPS() + " && " + p.nodeRunVPS("build"),
			Start:   p.nodeRunVPS("start"),
			Notes:   []string{"Ubuntu's Node.js may be older than your project needs; install a newer one (e.g. with nvm) in the VPS if the build fails."},
		},
	}
}

func nodeSPA(p *project) Detection {
	out, tool := "dist", "Vite"
	switch {
	case p.pkg.has("react-scripts"):
		out, tool = "build", "Create React App"
	case p.pkg.has("@angular/cli"):
		out, tool = "dist/"+p.pkg.Name+"/browser", "Angular"
	}
	nginxConf := `server { listen 80; root /usr/share/nginx/html; location / { try_files $uri $uri/ /index.html; } }`
	return Detection{
		Type: "node-spa", Label: "Node.js · " + tool + " static site", Port: 80,
		Dockerfile: strings.Join([]string{
			"# Generated by LPS: build the site with Node, serve it with nginx.",
			"FROM node:22-alpine AS build",
			"WORKDIR /app",
			nodeCopyManifests,
			"RUN " + p.nodeInstall(),
			"COPY . .",
			"RUN " + p.nodeRun("build"),
			"",
			"FROM nginx:1.27-alpine",
			"COPY --from=build /app/" + out + " /usr/share/nginx/html",
			"# Send unknown paths to index.html so client-side routing works.",
			"RUN echo '" + nginxConf + "' > /etc/nginx/conf.d/default.conf",
			"EXPOSE 80",
		}, "\n") + "\n",
		Notes: []string{"Assumes `" + p.nodeRun("build") + "` writes the site to `" + out + "/`. Change the COPY line if yours differs."},
		Run: RunSetup{
			Packages: nodePackages, Port: 3000,
			Install: p.nodeInstallVPS() + " && " + p.nodeRunVPS("build"),
			Start:   "npx --yes serve -s " + out + " -l tcp://0.0.0.0:$PORT",
			Notes:   []string{"Builds the site, then serves `" + out + "/` with `serve`."},
		},
	}
}

func nodeServer(p *project) Detection {
	start := p.nodeRun("start")
	notes := []string{"Your app should listen on the PORT environment variable (3000) and on 0.0.0.0, not localhost."}
	if p.pkg == nil || p.pkg.Scripts["start"] == "" {
		entry := ""
		if p.pkg != nil && p.pkg.Main != "" && p.exists(p.pkg.Main) {
			entry = p.pkg.Main
		}
		for _, f := range []string{"server.js", "index.js", "app.js", "main.js"} {
			if entry == "" && p.exists(f) {
				entry = f
			}
		}
		if entry == "" {
			entry = "index.js"
			notes = append(notes, "No start script or entry file found; edit the CMD line.")
		}
		start = "node " + entry
	}
	lines := []string{
		"# Generated by LPS for a Node.js server. Edit as needed.",
		"FROM node:22-alpine",
		"WORKDIR /app",
		nodeCopyManifests,
		"RUN " + p.nodeInstall(),
		"COPY . .",
	}
	if p.pkg != nil && p.pkg.Scripts["build"] != "" {
		lines = append(lines, "RUN "+p.nodeRun("build"))
	}
	lines = append(lines,
		"ENV NODE_ENV=production PORT=3000 HOST=0.0.0.0",
		"EXPOSE 3000",
		"CMD "+execForm(start),
	)
	install, vpsStart := p.nodeInstallVPS(), start
	if p.pkg != nil && p.pkg.Scripts["build"] != "" {
		install += " && " + p.nodeRunVPS("build")
	}
	if p.pkg != nil && p.pkg.Scripts["start"] != "" {
		vpsStart = p.nodeRunVPS("start")
	}
	return Detection{Type: "node", Label: "Node.js server", Port: 3000, Dockerfile: strings.Join(lines, "\n") + "\n", Notes: notes,
		Run: RunSetup{Packages: nodePackages, Install: install, Start: vpsStart, Port: 3000, Notes: notes}}
}

// ---- Python ----

func (p *project) pyModule() string {
	for _, f := range []string{"main.py", "app.py", "server.py", "wsgi.py", "run.py"} {
		if p.exists(f) {
			return strings.TrimSuffix(f, ".py")
		}
	}
	return "main"
}

var pyDepRe = func(dep string) *regexp.Regexp {
	return regexp.MustCompile(`(?m)(^|["'\s])` + regexp.QuoteMeta(dep) + `([\s=<>~!\[;"']|$)`)
}

func (p *project) pyHas(dep string) bool { return pyDepRe(dep).MatchString(p.pyDeps) }

func (p *project) pyBase(extra ...string) []string {
	lines := []string{
		"FROM python:3.12-slim",
		"ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PORT=8000",
		"WORKDIR /app",
	}
	if p.exists("requirements.txt") {
		lines = append(lines, "COPY requirements.txt ./", "RUN pip install --no-cache-dir -r requirements.txt")
	}
	missing := []string{}
	for _, e := range extra {
		if !p.pyHas(e) {
			missing = append(missing, e)
		}
	}
	if len(missing) > 0 {
		lines = append(lines, "RUN pip install --no-cache-dir "+strings.Join(missing, " "))
	}
	lines = append(lines, "COPY . .")
	if !p.exists("requirements.txt") && p.exists("pyproject.toml") {
		lines = append(lines, "RUN pip install --no-cache-dir .")
	}
	return append(lines, "EXPOSE 8000")
}

const pyPackages = "python3 python3-venv"

// pyRun installs into a virtualenv in the app folder.
func (p *project) pyRun(start string, extra ...string) RunSetup {
	steps := []string{"python3 -m venv .venv"}
	if p.exists("requirements.txt") {
		steps = append(steps, ".venv/bin/pip install -r requirements.txt")
	} else if p.exists("pyproject.toml") {
		steps = append(steps, ".venv/bin/pip install .")
	}
	missing := []string{}
	for _, e := range extra {
		if !p.pyHas(e) {
			missing = append(missing, e)
		}
	}
	if len(missing) > 0 {
		steps = append(steps, ".venv/bin/pip install "+strings.Join(missing, " "))
	}
	return RunSetup{Packages: pyPackages, Install: strings.Join(steps, " && "), Start: start, Port: 8000}
}

func djangoProject(p *project) string {
	if p.dir == "" {
		return "mysite"
	}
	entries, _ := os.ReadDir(p.dir)
	for _, e := range entries {
		if e.IsDir() && p.exists(e.Name()+"/wsgi.py") {
			return e.Name()
		}
	}
	return "mysite"
}

