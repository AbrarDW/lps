type template struct {
	id    string
	match func(p *project) bool
	gen   func(p *project) Detection
}

func isSPA(p *project) bool {
	if p.pkg == nil || p.pkg.Scripts["build"] == "" {
		return false
	}
	if !(p.pkg.has("vite") || p.pkg.has("react-scripts") || p.pkg.has("@angular/cli")) {
		return false
	}
	// A "start" that runs a real server (not just the dev server) means it is not a static site.
	start := p.pkg.Scripts["start"]
	return start == "" || strings.Contains(start, "vite") || strings.Contains(start, "react-scripts") || strings.HasPrefix(start, "ng ")
}

// templates in detection priority order.
var templates = []template{
	{"node-next", func(p *project) bool { return p.pkg.has("next") }, nodeNext},
	{"node-spa", isSPA, nodeSPA},
	{"node", func(p *project) bool { return p.pkg != nil }, nodeServer},
	{"python-django", func(p *project) bool { return p.exists("manage.py") }, pyDjango},
	{"python-fastapi", func(p *project) bool { return p.pyHas("fastapi") }, pyFastAPI},
	{"python-flask", func(p *project) bool { return p.pyHas("flask") }, pyFlask},
	{"python", func(p *project) bool {
		return p.exists("requirements.txt") || p.exists("pyproject.toml") || p.exists("main.py") || p.exists("app.py")
	}, pyGeneric},
	{"go", func(p *project) bool { return p.exists("go.mod") }, goApp},
	{"php", func(p *project) bool {
		return p.exists("composer.json") || p.exists("index.php") || p.exists("public/index.php")
	}, phpApp},
	{"static", func(p *project) bool { return p.exists("index.html") }, staticSite},
	{"custom", func(*project) bool { return true }, custom},
}

// Detect picks the best template for dir.
func Detect(dir string) Detection {
	p := inspect(dir)
	for _, t := range templates {
		if t.match(p) {
			return t.gen(p)
		}
	}
	return custom(p)
}

// Templates returns every template, generated for dir, for the UI's picker.
// With dir "" the templates are generic (for code LPS cannot read).
func Templates(dir string) []Detection {
	p := inspect(dir)
	if p.pkg == nil {
		p.pkg = &packageJSON{} // let Node templates render for non-Node folders
	}
	out := make([]Detection, 0, len(templates))
	for _, t := range templates {
		out = append(out, t.gen(p))
	}
	return out
}

